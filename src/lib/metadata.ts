import type { Metadata } from "next";
import { shareImage, site } from "@/lib/site";

// Builds per-page metadata with a canonical URL and matching social-share tags.
// Next.js replaces `openGraph`/`twitter` wholesale per page, so shared fields are repeated here.
export function pageMetadata({
  title,
  description,
  path,
}: {
  title: string;
  description: string;
  path: string;
}): Metadata {
  const fullTitle = title === site.name ? title : `${title} | ${site.name}`;
  return {
    title,
    description,
    alternates: { canonical: path },
    openGraph: {
      type: "website",
      locale: "en_US",
      siteName: site.name,
      url: path,
      title: fullTitle,
      description,
      images: [shareImage],
    },
    twitter: {
      card: "summary_large_image",
      title: fullTitle,
      description,
      images: [shareImage.url],
    },
  };
}
